# QuickLaunch build script (ASCII only on purpose: Windows PowerShell 5.1 misreads
# BOM-less UTF-8 as GBK, which breaks any non-ASCII text in .ps1 files)
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File build.ps1            build to dist\QuickLaunch.exe
#   powershell -ExecutionPolicy Bypass -File build.ps1 -Run       build then launch
#   powershell -ExecutionPolicy Bypass -File build.ps1 -ScanTest  build then run scanner self-test
#   powershell -ExecutionPolicy Bypass -File build.ps1 -UiCheck   build then dump DPI/layout diagnostics
#
# Requires nothing but the in-box C# compiler (.NET Framework 4.x).

param(
    [switch]$Run,
    [switch]$ScanTest,
    [switch]$UiCheck,
    [switch]$SpeedTest,
    [switch]$Debug,
    [int]$Icon = 1
)

$ErrorActionPreference = 'Stop'
$root   = $PSScriptRoot
$srcDir = Join-Path $root 'src'
$outDir = Join-Path $root 'dist'
$exe    = Join-Path $outDir 'QuickLaunch.exe'
$iconDir = Join-Path $root 'icons'

# ---- pick the app icon (icons\concept-N.ico generated by tools\make-icons.py)
$iconFile = Join-Path $iconDir ("concept-$Icon.ico")
$appIcon  = Join-Path $iconDir 'app.ico'
$useIcon  = $false
if (Test-Path -LiteralPath $iconFile) {
    Copy-Item -LiteralPath $iconFile -Destination $appIcon -Force
    $useIcon = $true
} elseif (Test-Path -LiteralPath $appIcon) {
    $useIcon = $true
}

# ---- locate the compiler
# Prefer Roslyn (C# 12, better diagnostics and faster); fall back to the in-box csc (C# 5).
$csc = $null
$cscLabel = ""
$roslyn = @(
    "E:\visual studio IDE\MSBuild\Current\Bin\Roslyn\csc.exe",
    "C:\Program Files\Microsoft Visual Studio\2022\Community\MSBuild\Current\Bin\Roslyn\csc.exe",
    "D:\Program Files\Microsoft Visual Studio\2022\Community\MSBuild\Current\Bin\Roslyn\csc.exe",
    "E:\Program Files\Microsoft Visual Studio\2022\Community\MSBuild\Current\Bin\Roslyn\csc.exe"
)
foreach ($c in $roslyn) {
    if (Test-Path -LiteralPath $c) { $csc = $c; $cscLabel = "Roslyn (modern C#)"; break }
}
if (-not $csc) {
    foreach ($c in @(
        "$env:SystemRoot\Microsoft.NET\Framework64\v4.0.30319\csc.exe",
        "$env:SystemRoot\Microsoft.NET\Framework\v4.0.30319\csc.exe")) {
        if (Test-Path -LiteralPath $c) { $csc = $c; $cscLabel = "Inbox csc (C# 5 only)"; break }
    }
}
if (-not $csc) { throw "C# compiler not found. Is .NET Framework 4.x installed?" }

$files = Get-ChildItem -LiteralPath $srcDir -Filter *.cs | Sort-Object Name | Select-Object -ExpandProperty FullName
if ($files.Count -eq 0) { throw "No .cs files in src." }

$manifest = Join-Path $srcDir 'app.manifest'
if (-not (Test-Path -LiteralPath $manifest)) { throw "Missing src\app.manifest (DPI awareness)." }

New-Item -ItemType Directory -Force -Path $outDir | Out-Null

Write-Host ""
Write-Host "QuickLaunch build" -ForegroundColor Cyan
Write-Host "  compiler : $cscLabel"
Write-Host "  path     : $csc"
Write-Host "  sources  : $($files.Count) files"
Write-Host "  manifest : app.manifest (DPI aware / asInvoker)"
Write-Host ("  icon     : {0}" -f $(if ($useIcon) { $appIcon } else { "(none)" }))
Write-Host "  output   : $exe"
Write-Host ""

$sw = [System.Diagnostics.Stopwatch]::StartNew()

$cscArgs = @(
    '/nologo',
    '/target:winexe',
    '/platform:anycpu',
    '/optimize+',
    "/win32manifest:$manifest",
    "/out:$exe",
    '/reference:System.dll,System.Drawing.dll,System.Windows.Forms.dll',
    '/warn:4'
)
if ($useIcon) { $cscArgs += "/win32icon:$appIcon" }
if ($Debug) { $cscArgs += '/debug+'; $cscArgs += '/define:DEBUG' }
$cscArgs += $files

$output = & $csc $cscArgs 2>&1
$code = $LASTEXITCODE
$sw.Stop()
if ($output) { $output | ForEach-Object { Write-Host $_ } }
if ($code -ne 0) {
    Write-Host ""
    Write-Host "BUILD FAILED (exit $code)" -ForegroundColor Red
    exit $code
}

$info = Get-Item -LiteralPath $exe
Write-Host ""
Write-Host "BUILD OK" -ForegroundColor Green
Write-Host ("  file : {0}" -f $info.FullName)
Write-Host ("  size : {0:N0} bytes ({1:N0} KB)" -f $info.Length, ($info.Length / 1KB))
Write-Host ("  time : {0} ms" -f $sw.ElapsedMilliseconds)
Write-Host ""

# ---- diagnostic build (console subsystem) ----
# A /target:winexe app cannot print to the console it was launched from, so every
# --diagnostic mode looked like "the command did nothing". This second build is the
# same sources with /target:exe, so its output goes straight to the cmd window.
$diag = Join-Path $outDir 'QuickLaunchDiag.exe'
Write-Host "Building diagnostic console exe ..." -ForegroundColor Cyan
$diagArgs = @(
    '/nologo',
    '/target:exe',
    '/platform:anycpu',
    '/optimize+',
    "/win32manifest:$manifest",
    "/out:$diag",
    '/reference:System.dll,System.Drawing.dll,System.Windows.Forms.dll',
    '/warn:4'
) + $files
if ($useIcon) { $diagArgs += "/win32icon:$appIcon" }
$diagOut = & $csc $diagArgs 2>&1
if ($LASTEXITCODE -ne 0) {
    if ($diagOut) { $diagOut | ForEach-Object { Write-Host $_ } }
    Write-Host "  [WARN] diagnostic exe failed to build (main exe is still fine)" -ForegroundColor Yellow
} else {
    $di = Get-Item -LiteralPath $diag
    Write-Host ("  diag : {0} ({1:N0} KB)   <-- use THIS one for --launch-one / --uicheck" -f $di.Name, ($di.Length / 1KB)) -ForegroundColor Green
}
Write-Host ""

# ---- optional: window speed check (off by default, it briefly opens windows)
if ($SpeedTest) {
    Write-Host "Startup speed check (window must exist after 700ms):" -ForegroundColor Cyan
    foreach ($i in 1..3) {
        $t = [System.Diagnostics.Stopwatch]::StartNew()
        $p = Start-Process -FilePath $exe -PassThru
        Start-Sleep -Milliseconds 700
        $t.Stop()
        $alive = -not $p.HasExited
        if ($alive) { $p.CloseMainWindow() | Out-Null; Start-Sleep -Milliseconds 400 }
        if (-not $p.HasExited) { $p.Kill() }
        Write-Host ("  run {0}: window {1} (within {2} ms)" -f $i, $(if ($alive) { "OK" } else { "MISSING" }), $t.ElapsedMilliseconds)
    }
    Write-Host ""
}

if ($ScanTest) {
    Write-Host "Running scanner self-test (--scan) ..." -ForegroundColor Cyan
    & $exe --scan
    Write-Host ""
}

if ($UiCheck) {
    Write-Host "Running layout/DPI diagnostics (--uicheck) ..." -ForegroundColor Cyan
    & $exe --uicheck
    Write-Host ""
}

if ($Run) {
    Write-Host "Launching ..." -ForegroundColor Cyan
    Start-Process -FilePath $exe
}

Write-Host "DONE." -ForegroundColor Green
